-- 迁移执行完毕后运行：把最小权限授予应用账号。
-- app_password 由 psql 变量传入（-v app_password=...）。
ALTER ROLE exam_app PASSWORD :'app_password';

GRANT CONNECT ON DATABASE exam TO exam_app;
GRANT USAGE ON SCHEMA iam, catalog, authoring, audit, delivery, app, grading TO exam_app;

-- iam schema：业务表需要读写
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA iam TO exam_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA iam TO exam_app;

-- catalog schema：题库与内容上下文，业务表需要读写
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA catalog TO exam_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA catalog TO exam_app;

-- authoring schema：组卷上下文，业务表需要读写
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA authoring TO exam_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA authoring TO exam_app;

-- delivery schema：考试组织与作答上下文，业务表需要读写
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA delivery TO exam_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA delivery TO exam_app;

-- grading schema：评分与阅卷，业务表需要读写
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA grading TO exam_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA grading TO exam_app;

-- app schema：追加式流水，只允许写入与查询
GRANT SELECT, INSERT ON ALL TABLES IN SCHEMA app TO exam_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA app TO exam_app;
REVOKE UPDATE, DELETE ON ALL TABLES IN SCHEMA app FROM exam_app;

-- audit schema：追加式，只允许写入与查询
GRANT SELECT, INSERT ON ALL TABLES IN SCHEMA audit TO exam_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA audit TO exam_app;
REVOKE UPDATE, DELETE ON ALL TABLES IN SCHEMA audit FROM exam_app;


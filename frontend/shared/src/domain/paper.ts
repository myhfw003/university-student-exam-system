/* ==========================================================================
   知行测评 · 试卷状态（服务端口径）
   --------------------------------------------------------------------------
   试卷在服务端是三态：`draft` / `published` / `archived`。
   这三个码是**前后端共享的词表**：
   - 后端按它们判状态流转（发布 / 撤回 / 归档都认这几个码，
     列表接口的 `status` 参数也只认这几个值）；
   - 前端按它们判断「这份试卷现在算什么状态」（能不能发、能不能改、
     是不是已经归档）。

   与 `types.ts` 里 mock 用的「进行中 / 已结束」不是一回事：
   那是前端原型自己加的运行时状态，**HTTP 模式只用服务端的三态**。

   两边对不上时 CI 会报错（`scripts/check-paper-status-codes.py`）：
   前端写错一个码，后端不认 → 端点直接判「试卷状态取值不合法。」，
   而单元测试全绿。

   **中文名不在前端另立一套**：试卷的中文名（草稿 / 已发布 / 已归档）
   由服务端随 `statusLabel` 一起给，前端照抄——服务端改文案时
   管理端不会显示成另一个名字。
   ========================================================================== */

/** 服务端的试卷状态码（与后端 `PaperStatuses` 一一对应）。 */
export const PAPER_STATUS = {
  draft: "draft",
  published: "published",
  archived: "archived",
} as const;

/** 试卷状态。 */
export type PaperStatus = (typeof PAPER_STATUS)[keyof typeof PAPER_STATUS];
